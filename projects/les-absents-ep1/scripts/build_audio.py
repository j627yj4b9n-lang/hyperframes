#!/usr/bin/env python3
"""Generate the episode's dialogue, lip-sync envelopes, subtitle and audio tags.

ElevenLabs first (the four chosen voices). If the API refuses (no valid key),
falls back to Edge neural voices so the cut stays complete; re-run this script
once the key works and every line is regenerated with the ElevenLabs voices.

  python3 scripts/build_audio.py            # ElevenLabs, else fallback
  python3 scripts/build_audio.py --force-eleven   # fail instead of falling back
"""
import json, os, re, subprocess, sys, urllib.request, urllib.error, ssl, asyncio
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CFG = json.load(open(os.path.join(ROOT, "scripts", "lines.json")))
OUT = os.path.join(ROOT, "assets", "audio")
RAW = os.path.join(ROOT, "scripts", ".raw")
os.makedirs(OUT, exist_ok=True)
os.makedirs(RAW, exist_ok=True)
FORCE = "--force-eleven" in sys.argv
CA = "/root/.ccr/ca-bundle.crt"
CTX = ssl.create_default_context(cafile=CA) if os.path.exists(CA) else ssl.create_default_context()


def eleven(voice_id, text, model, stability, out):
    body = {
        "text": text,
        "model_id": model,
        "voice_settings": {"stability": stability, "similarity_boost": 0.85, "style": 0.35, "use_speaker_boost": True},
        "language_code": "fr",
    }
    if model == "eleven_v3":
        body["voice_settings"] = {"stability": 0.5}
    req = urllib.request.Request(
        f"https://api.elevenlabs.io/v1/text-to-speech/{voice_id}?output_format=mp3_44100_192",
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json", "xi-api-key": "proxy-injected"},
    )
    with urllib.request.urlopen(req, context=CTX, timeout=120) as r:
        data = r.read()
    open(out, "wb").write(data)


def edge(voice, text, rate, pitch, out):
    import edge_tts, edge_tts.communicate as c
    c._SSL_CTX = CTX
    asyncio.run(edge_tts.Communicate(text, voice, rate=rate, pitch=pitch).save(out))


def sh(*a):
    return subprocess.run(a, check=True, capture_output=True)


def dur(f):
    return float(sh("ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f).stdout)


engine_used = None
results = []
for ln in CFG["lines"]:
    v = CFG["voices"][ln["who"]]
    raw = os.path.join(RAW, ln["id"] + ".mp3")
    got = False
    if engine_used in (None, "elevenlabs"):
        for model, text in (("eleven_v3", f'{ln["v3"]} {ln["text"]}'), ("eleven_multilingual_v2", ln["text"])):
            try:
                eleven(v["elevenlabs"], text, model, ln.get("stability", 0.45), raw)
                got, engine_used = True, "elevenlabs"
                print(ln["id"], "elevenlabs", model)
                break
            except urllib.error.HTTPError as e:
                print(ln["id"], model, "HTTP", e.code, e.read()[:160].decode(errors="ignore"))
                if e.code in (401, 403) and model == "eleven_multilingual_v2":
                    break
    if not got:
        if FORCE:
            sys.exit("ElevenLabs refused and --force-eleven was given")
        engine_used = "edge"
        edge(v["edge"], ln["text"], v["edgeRate"], v["edgePitch"], raw)
        print(ln["id"], "edge", v["edge"])

    # clean: trim edge silence, gentle high-pass + presence, loudness to -16 LUFS, true peak -1.5
    clean = os.path.join(RAW, ln["id"] + ".wav")
    sh("ffmpeg", "-y", "-i", raw, "-af",
       "silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,"
       "highpass=f=75,equalizer=f=3200:t=q:w=1.2:g=2.5,loudnorm=I=-16:TP=-1.5:LRA=9",
       "-ar", "48000", "-ac", "1", clean)
    d = dur(clean)
    tempo = 1.0
    if d > ln["slot"]:
        tempo = min(1.12, d / ln["slot"])
    final = os.path.join(OUT, ln["id"] + ".m4a")
    sh("ffmpeg", "-y", "-i", clean, "-af", f"atempo={tempo:.4f},apad=pad_dur=0.05", "-c:a", "aac", "-b:a", "192k", final)
    d = dur(final)
    pcm = sh("ffmpeg", "-v", "error", "-i", final, "-f", "s16le", "-ac", "1", "-ar", "48000", "-").stdout
    s = np.frombuffer(pcm, dtype=np.int16).astype(np.float32) / 32768
    hop = 48000 // 30
    env = [float(np.sqrt(np.mean(s[i:i + hop] ** 2))) for i in range(0, len(s), hop)]
    p = np.percentile(env, 92) or 1
    env = [round(min(1.0, e / p), 3) for e in env]
    results.append({**{k: ln[k] for k in ("id", "who", "start", "text")}, "dur": round(d, 3), "tempo": round(tempo, 3), "env": env})
    flag = "  <-- OVER SLOT" if d > ln["slot"] + 0.05 else ""
    print(f'  {ln["id"]} {d:.2f}s (slot {ln["slot"]}) tempo {tempo:.2f}{flag}')

with open(os.path.join(ROOT, "assets", "timing.js"), "w") as f:
    f.write("// generated by scripts/build_audio.py — do not edit by hand\n")
    f.write(f"window.HF_VOICE_ENGINE = {json.dumps(engine_used)};\n")
    f.write("window.HF_LINES = " + json.dumps(results, ensure_ascii=False) + ";\n")

# inject <audio> tags and subtitle clips into index.html
idx = os.path.join(ROOT, "index.html")
html = open(idx).read()
aud = "\n".join(
    f'      <audio id="vo-{r["id"].lower()}" class="clip" src="assets/audio/{r["id"]}.m4a" data-start="{r["start"]}" '
    f'data-duration="{r["dur"]}" data-track-index="{20 + i}" data-volume="1"></audio>'
    for i, r in enumerate(results)
)
subs = "\n".join(
    f'      <div id="sub-{r["id"].lower()}" class="clip sub sub-{r["who"]}" data-start="{r["start"]}" '
    f'data-duration="{round(r["dur"] + 0.35, 3)}" data-track-index="10"><span>{r["text"]}</span></div>'
    for r in results
)
html = re.sub(r"(<!-- VO:BEGIN -->).*?(\s*<!-- VO:END -->)", lambda m: m.group(1) + "\n" + aud + m.group(2), html, flags=re.S)
html = re.sub(r"(<!-- SUBS:BEGIN -->).*?(\s*<!-- SUBS:END -->)", lambda m: m.group(1) + "\n" + subs + m.group(2), html, flags=re.S)
open(idx, "w").write(html)
print("engine:", engine_used)
